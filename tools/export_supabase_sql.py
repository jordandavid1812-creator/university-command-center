"""Write (or check) the numbered SQL files for Supabase's SQL editor, from the Django migrations.

    python tools/export_supabase_sql.py --write   # add files for any new migrations
    python tools/export_supabase_sql.py --check   # CI: committed files match the migrations

Needs a disposable PLAIN PostgreSQL 17 server (never Supabase, never real data) through PGHOST,
PGPORT, PGUSER and PGPASSWORD, with a user that may create databases and roles. It creates the
scratch database ucc_supabase_export (dropped first) and the roles ucc_runtime and ucc_auth
there, migrates it and records exactly what configure_auth_role and configure_runtime grant.

Files in supabase/migrations/, run in order in the SQL editor:
  NNNN_schema.sql    tables, constraints and row-level security for the listed migrations
  NNNN_security.sql  the website's restricted logins, Supabase public-API lock-down, RLS on every
                     table and the exact grants. Always re-run the newest one after a schema file.
Passwords and the signing key are never in these files: tools/supabase_secrets.py makes a
private file for that.
"""
import argparse
import os
from pathlib import Path
import re
import sys

REPO = Path(__file__).resolve().parents[1]
FOLDER = REPO / 'supabase' / 'migrations'
SCRATCH = 'ucc_supabase_export'
ROLES = {'runtime': 'ucc_runtime', 'auth': 'ucc_auth'}
API_ROLES = ('anon', 'authenticated', 'service_role')
SUPABASE_DATABASE = 'postgres'
# Supabase installs pgcrypto in its own "extensions" schema, and an extension can exist only once.
# Migration academics.0004 installs it in ucc_crypto; on Supabase ucc_crypto gets a private
# wrapper with the same name and arguments instead (owned by the SQL editor's postgres role).
PGCRYPTO = 'CREATE EXTENSION pgcrypto WITH SCHEMA ucc_crypto;'
PGCRYPTO_SUPABASE = ('CREATE FUNCTION ucc_crypto.hmac(bytea, bytea, text) RETURNS bytea\n'
                     'LANGUAGE sql IMMUTABLE STRICT SET search_path = pg_catalog\n'
                     'AS $wrapper$ SELECT extensions.hmac($1, $2, $3) $wrapper$;\n'
                     'REVOKE ALL ON FUNCTION ucc_crypto.hmac(bytea, bytea, text) FROM PUBLIC;')
HEADER = '''-- University Command Center: Supabase {kind} file {number:04d}. Generated by
-- tools/export_supabase_sql.py from the Django migrations; do not edit by hand.
-- Supabase dashboard > SQL Editor > New query: paste ALL of this file and press Run.
-- Run the files in number order. Do not save this query as a snippet.
'''


def setup_django():
    import psycopg
    admin = dict(host=os.environ.get('PGHOST', '127.0.0.1'), port=os.environ.get('PGPORT', '5432'),
                 user=os.environ['PGUSER'], password=os.environ.get('PGPASSWORD') or None, dbname='postgres',
                 autocommit=True)
    with psycopg.connect(**admin) as connection:
        connection.execute(f'DROP DATABASE IF EXISTS {SCRATCH}')
        connection.execute(f'CREATE DATABASE {SCRATCH}')
        for role in ROLES.values():
            if not connection.execute('SELECT 1 FROM pg_roles WHERE rolname = %s', [role]).fetchone():
                connection.execute(f'CREATE ROLE {role} LOGIN NOINHERIT NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE')
    os.environ.update(PGDATABASE=SCRATCH, DJANGO_SECRET_KEY='export-only-not-a-secret',
                      UCC_CONTEXT_SIGNING_KEY='00' * 32, UCC_RUNTIME_ROLE=ROLES['runtime'],
                      UCC_AUTH_ROLE=ROLES['auth'], DJANGO_SETTINGS_MODULE='config.settings.auth_migration')
    sys.path[:0] = [str(REPO / 'server'), str(REPO)]
    import django
    django.setup()


def all_migrations():
    from django.db import connection
    from django.db.migrations.executor import MigrationExecutor
    executor = MigrationExecutor(connection)
    return executor, executor.migration_plan(executor.loader.graph.leaf_nodes(), clean_start=True)


def schema_sql(executor, plan, number, first):
    from django.db import connection
    from django.db.migrations.recorder import MigrationRecorder
    names = [f'{m.app_label}.{m.name}' for m, _ in plan]
    lines = [HEADER.format(kind='schema', number=number)]
    lines += [f'-- migration: {name}' for name in names]
    lines.append('\nBEGIN;\n')
    if first:
        with connection.schema_editor(collect_sql=True, atomic=False) as editor:
            editor.create_model(MigrationRecorder.Migration)
        lines += editor.collected_sql
    for statement in executor.loader.collect_sql(plan):
        if PGCRYPTO in statement:
            if statement.count(PGCRYPTO) != 1:
                raise SystemExit('Unexpected pgcrypto statement shape; review the Supabase wrapper.')
            statement = statement.replace(PGCRYPTO, PGCRYPTO_SUPABASE)
        lines.append(statement)
    lines.append('INSERT INTO "django_migrations" ("app", "name", "applied") VALUES\n' + ',\n'.join(
        f"    ('{m.app_label}', '{m.name}', now())" for m, _ in plan) + ';')
    lines.append('\nCOMMIT;\n')
    return '\n'.join(lines)


def captured_grants():
    """Exactly what configure_auth_role and configure_runtime run (GRANT/REVOKE only; never the key)."""
    from django.core.management import call_command
    from django.db import connection
    captured = []

    def record(execute, sql, params, many, context):
        text = sql if isinstance(sql, str) else sql.as_string(context['cursor'].cursor.connection)
        if re.match(r'\s*(GRANT|REVOKE)\b', text) and not params:
            captured.append(text.strip() + ';')
        return execute(sql, params, many, context)

    call_command('migrate', verbosity=0)
    with connection.execute_wrapper(record):
        call_command('configure_auth_role', verbosity=0)
        call_command('configure_runtime', verbosity=0)
    scratch, real = f'"{SCRATCH}"', f'"{SUPABASE_DATABASE}"'
    return [statement.replace(scratch, real) for statement in captured]


def tables_and_auth_tables():
    from django.db import connection
    with connection.cursor() as cursor:
        cursor.execute('''SELECT c.relname, c.relrowsecurity,
                                 has_table_privilege(%s, c.oid, 'SELECT, INSERT, UPDATE, DELETE')
                                 OR has_any_column_privilege(%s, c.oid, 'SELECT, INSERT, UPDATE')
                          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                          WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') ORDER BY c.relname''',
                       [ROLES['auth'], ROLES['auth']])
        return cursor.fetchall()


def security_sql(number):
    grants = captured_grants()
    tables = tables_and_auth_tables()
    runtime, auth = ROLES['runtime'], ROLES['auth']
    lines = [HEADER.format(kind='security', number=number), '''-- 1. The website's two restricted logins (passwords are set by your private file, never here).
--    LOGIN NOINHERIT and no superuser, bypass-RLS, create-database or create-role rights.
BEGIN;
DO $roles$
BEGIN
''']
    for role in (runtime, auth):
        lines.append(f'''    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{role}') THEN
        CREATE ROLE {role} LOGIN NOINHERIT NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
    END IF;''')
    lines.append('''END
$roles$;

-- 2. Supabase's public Data API logins (anon, authenticated, service_role) get NOTHING here:
--    not today's tables, functions or sequences, and not tables created later by postgres.
DO $api$
DECLARE
    api text;
BEGIN
    FOR api IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role') LOOP
        EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public, ucc_security FROM %I', api);
        EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public, ucc_security FROM %I', api);
        EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public, ucc_security, ucc_crypto FROM %I', api);
        EXECUTE format('REVOKE ALL ON SCHEMA ucc_security, ucc_crypto FROM %I', api);
        EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON TABLES FROM %I', api);
        EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON SEQUENCES FROM %I', api);
        EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM %I', api);
    END LOOP;
END
$api$;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA ucc_security, ucc_crypto FROM PUBLIC;
-- Functions in public (Supabase adds rls_auto_enable, its own event-trigger helper) are not
-- callable through the Data API either. Event triggers still run: firing checks no EXECUTE right.
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;

-- 3a. The grants below take CONNECT and TEMPORARY on this database away from PUBLIC, so the
--     website logins cannot make temporary objects. Every OTHER existing login (Supabase's own:
--     the pooler, Storage, Auth, the Data API and the dashboard) keeps exactly those rights.
DO $keep$
DECLARE
    other text;
BEGIN
    FOR other IN SELECT rolname FROM pg_roles
                 WHERE rolname !~ '^pg_' AND NOT rolsuper AND rolname NOT IN ('ucc_runtime', 'ucc_auth') LOOP
        EXECUTE format('GRANT CONNECT, TEMPORARY ON DATABASE postgres TO %I', other);
    END LOOP;
END
$keep$;

-- 3. The exact grants of configure_auth_role and configure_runtime (same as the local website).''')
    lines += grants
    lines.append('''
-- 4. Row-level security on EVERY table. Student tables already force it (owner rows only).
--    Account and sign-in tables: only the auth login, through an explicit policy.
--    Django's own bookkeeping tables: no policy, so no other login can read them.''')
    for table, secured, auth_uses in tables:
        if secured:
            continue
        lines.append(f'ALTER TABLE public.{table} ENABLE ROW LEVEL SECURITY;')
        if auth_uses:
            lines.append(f'DROP POLICY IF EXISTS ucc_auth_access ON public.{table};')
            lines.append(f'CREATE POLICY ucc_auth_access ON public.{table} FOR ALL TO {auth} USING (true) WITH CHECK (true);')
    lines.append(f'''
-- 5. Self-check: stop with an error if any Data API login can still reach a table or function.
DO $check$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles r CROSS JOIN pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
               WHERE r.rolname IN ('anon', 'authenticated', 'service_role')
                 AND n.nspname IN ('public', 'ucc_security') AND c.relkind IN ('r', 'p', 'v', 'm')
                 AND (has_table_privilege(r.oid, c.oid, 'SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER')
                      OR has_any_column_privilege(r.oid, c.oid, 'SELECT, INSERT, UPDATE, REFERENCES')))
    THEN
        RAISE EXCEPTION 'A Supabase Data API login can still reach a University Command Center table.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
               WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relrowsecurity) THEN
        RAISE EXCEPTION 'A table in public has no row-level security.';
    END IF;
END
$check$;
COMMIT;
''')
    return '\n'.join(lines)


def existing_files():
    files = sorted(FOLDER.glob('[0-9][0-9][0-9][0-9]_*.sql')) if FOLDER.exists() else []
    covered = []
    for path in files:
        if path.name.endswith('_schema.sql'):
            covered += re.findall(r'^-- migration: (\S+)$', path.read_text(), re.M)
    return files, covered


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true', help='Add schema/security files for new migrations.')
    mode.add_argument('--check', action='store_true', help='Fail if the committed files are out of date.')
    values = parser.parse_args(argv)
    setup_django()
    executor, plan = all_migrations()
    files, covered = existing_files()
    by_name = {f'{m.app_label}.{m.name}': (m, b) for m, b in plan}
    problems = []
    # Every committed schema file must still equal what its migrations produce.
    start = 0
    for path in files:
        if path.name.endswith('_schema.sql'):
            names = re.findall(r'^-- migration: (\S+)$', path.read_text(), re.M)
            if any(name not in by_name for name in names):
                problems.append(f'{path.name} lists a migration that no longer exists')
                continue
            expected = schema_sql(executor, [by_name[name] for name in names], int(path.name[:4]), start == 0)
            start += len(names)
            if path.read_text() != expected:
                problems.append(f'{path.name} does not match its migrations')
    missing = [entry for entry in plan if f'{entry[0].app_label}.{entry[0].name}' not in covered]
    number = int(files[-1].name[:4]) + 1 if files else 1
    security_files = [path for path in files if path.name.endswith('_security.sql')]
    if values.check:
        if missing:
            problems.append(f'{len(missing)} migration(s) have no Supabase schema file: run --write')
        elif not security_files or files[-1] != security_files[-1]:
            problems.append('the newest file must be a security file: run --write')
        else:
            expected = security_sql(int(security_files[-1].name[:4]))
            if security_files[-1].read_text() != expected:
                problems.append(f'{security_files[-1].name} does not match the current grants: run --write')
        if problems:
            sys.exit('Supabase SQL files are out of date:\n  ' + '\n  '.join(problems))
        print(f'Supabase SQL files are up to date ({len(files)} files, {len(covered)} migrations).')
        return
    if problems:
        sys.exit('Refusing to write: committed files were edited or migrations removed:\n  ' + '\n  '.join(problems))
    if not missing:
        if security_files and security_files[-1] == files[-1] and \
                security_files[-1].read_text() == security_sql(int(security_files[-1].name[:4])):
            print('No new migrations and the grants are unchanged; nothing written.')
            return
        (FOLDER / f'{number:04d}_security.sql').write_text(security_sql(number))
        print(f'Wrote {number:04d}_security.sql (grants changed).')
        return
    FOLDER.mkdir(parents=True, exist_ok=True)
    (FOLDER / f'{number:04d}_schema.sql').write_text(schema_sql(executor, missing, number, not covered))
    (FOLDER / f'{number + 1:04d}_security.sql').write_text(security_sql(number + 1))
    print(f'Wrote {number:04d}_schema.sql ({len(missing)} migrations) and {number + 1:04d}_security.sql.')


if __name__ == '__main__':
    main()
